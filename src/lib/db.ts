import { PrismaClient } from "@prisma/client";
import { PrismaLibSQL } from "@prisma/adapter-libsql/web";
import { resolveDatabaseTarget } from "./database-url";

const globalForPrisma = globalThis as unknown as {
  prisma: PrismaClient | undefined;
};

/**
 * Local development, the seed script and the mock harness all run against a
 * SQLite file (DATABASE_URL="file:./dev.db"). A serverless deployment cannot:
 * its filesystem is read-only and each instance gets its own copy, which fails
 * with "Error code 14: Unable to open the database file".
 *
 * Two hosted setups work without touching any query:
 *   - Postgres, which the client generated by `npm run build` targets directly;
 *   - Turso / libSQL, which needs Prisma's driver adapter because Prisma
 *     Migrate and the default client only speak SQLite over a local file.
 */
function createPrismaClient(): PrismaClient {
  const target = resolveDatabaseTarget();

  if (target.kind === "libsql") {
    return new PrismaClient({
      adapter: new PrismaLibSQL({
        url: target.url!,
        authToken: process.env.TURSO_AUTH_TOKEN,
      }),
    });
  }

  if (process.env.NODE_ENV === "production" && target.kind === "sqlite") {
    console.error(
      `[db] ${target.source} is a local SQLite file, which a serverless deployment cannot open. ` +
        "Point DATABASE_URL at a Postgres database (or TURSO_DATABASE_URL at a libsql:// database)."
    );
  }

  return new PrismaClient();
}

export const prisma = globalForPrisma.prisma ?? createPrismaClient();

if (process.env.NODE_ENV !== "production") globalForPrisma.prisma = prisma;
